fn pattern() -> Vec<u8> {
    let period: Vec<u8> = (0..600u32).map(|i| ((i * i * 31 + i) % 256) as u8).collect();
    period.repeat(30)
}

#[test]
fn stored_blocks_decompress() {
    assert_eq!(zlib_decompress(STORED_EMPTY).unwrap(), b"");
    assert_eq!(zlib_decompress(STORED).unwrap(), TEXT);
}

#[test]
fn fixed_huffman_blocks_decompress() {
    assert_eq!(zlib_decompress(FIXED).unwrap(), TEXT);
}

#[test]
fn dynamic_huffman_blocks_decompress() {
    assert_eq!(zlib_decompress(DYNAMIC).unwrap(), PANGRAM.repeat(20));
}

#[test]
fn copies_reach_back_far_and_at_their_longest() {
    assert_eq!(zlib_decompress(LONG_DISTANCES).unwrap(), pattern());
}

#[test]
fn adler32_matches_the_specification() {
    // RFC 1950's example of the checksum.
    assert_eq!(adler32(b"Wikipedia"), 0x11E6_0398);
    assert_eq!(adler32(b""), 1);
}

#[test]
fn a_wrong_checksum_fails() {
    let mut broken = DYNAMIC.to_vec();
    *broken.last_mut().unwrap() ^= 1;
    let error = zlib_decompress(&broken).unwrap_err();
    assert!(error.contains("checksum"), "{error}");
}

#[test]
fn a_stream_cut_short_fails() {
    for length in [0, 1, 2, 5, DYNAMIC.len() / 2, DYNAMIC.len() - 1] {
        assert!(zlib_decompress(&DYNAMIC[..length]).is_err(), "{length} bytes decompressed");
    }
}

#[test]
fn headers_that_aren_t_deflate_without_a_dictionary_fail() {
    // Method 7 instead of 8.
    assert!(zlib_decompress(&[0x77, 0x01, 0x01, 0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x01]).is_err());
    // The header check, (0x78 * 256 + 0x02) % 31, isn't 0.
    assert!(zlib_decompress(&[0x78, 0x02, 0x01, 0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x01]).is_err());
    // 0x20: a preset dictionary, with a valid header check.
    let error = zlib_decompress(&[0x78, 0x20, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01]).unwrap_err();
    assert!(error.contains("dictionary"), "{error}");
}

#[test]
fn a_stored_block_whose_length_doesn_t_match_its_complement_fails() {
    let error = zlib_decompress(&[0x78, 0x01, 0x01, 0x01, 0x00, 0xFF, 0xFF, 0x41, 0x00, 0x42, 0x00, 0x42]).unwrap_err();
    assert!(error.contains("complement"), "{error}");
}

#[test]
fn block_type_3_fails() {
    // Final, type 3: bits 1, 1, 1.
    let error = zlib_decompress(&[0x78, 0x01, 0x07, 0x00, 0x00, 0x00, 0x00, 0x01]).unwrap_err();
    assert!(error.contains("type 3"), "{error}");
}
